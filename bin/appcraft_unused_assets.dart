import 'dart:io';

import 'package:appcraft_unused_assets/appcraft_unused_assets.dart';
import 'package:args/args.dart';
import 'package:path/path.dart' as p;
import 'package:yaml/yaml.dart';

const String _usageHeader = '''
Finds the assets that nothing in the project refers to.

Usage: appcraft_unused_assets <command> [options]

Commands:
  report   list the assets nothing refers to
  check    exit with 1 if anything is unused (for CI)
  clean    delete the files of the unused assets
''';

Future<void> main(List<String> arguments) async {
  final parser = ArgParser()
    ..addOption('generated', help: 'File generated by flutter_gen.')
    ..addMultiOption('scan', help: 'Directory to scan for usages.')
    ..addFlag('dry-run', negatable: false, help: 'Report without deleting.')
    ..addFlag('help', abbr: 'h', negatable: false);

  final ArgResults options;
  try {
    options = parser.parse(arguments);
  } on FormatException catch (e) {
    _fail('${e.message}\n\n$_usageHeader${parser.usage}');
  }

  if (options['help'] as bool || options.rest.isEmpty) {
    stdout.writeln('$_usageHeader\n${parser.usage}');
    return;
  }

  final command = options.rest.first;
  if (!_commands.contains(command)) {
    _fail('Unknown command "$command".\n\n$_usageHeader');
  }

  final root = Directory.current.path;
  final pubspec = File(p.join(root, 'pubspec.yaml'));
  if (!pubspec.existsSync()) {
    _fail('pubspec.yaml not found in $root.');
  }

  final UnusedAssetsFinder finder;
  final UnusedAssetsReport report;
  try {
    final build = File(p.join(root, 'build.yaml'));
    final fromFile = UnusedAssetsConfig.fromPubspec(
      pubspec.readAsStringSync(),
      build: build.existsSync() ? build.readAsStringSync() : null,
    );
    final scan = options['scan'] as List<String>;
    final config = UnusedAssetsConfig(
      generated: options['generated'] as String? ?? fromFile.generated,
      scan: scan.isEmpty ? fromFile.scan : scan,
      ignore: fromFile.ignore,
      entryPoints: fromFile.entryPoints,
    );

    finder = UnusedAssetsFinder(
      config: config,
      root: root,
    );
    if (!finder.generatedFile.existsSync()) {
      _fail(
        'Generated file not found: ${config.generated}\n'
        'This tool reads the accessors generated by flutter_gen. Generate them '
        'with "dart run build_runner build", or point at the file with '
        '--generated if it lives elsewhere.',
      );
    }

    report = finder.find();
  } on YamlException catch (e) {
    _fail('$e');
  }

  switch (command) {
    case 'report':
      _write(
        report,
        stdout,
        hint: '\nCheck them before deleting: an asset addressed by a path '
            'built at runtime looks unused here.',
      );
    case 'check':
      if (report.unused.isEmpty) {
        _write(report, stdout);
        return;
      }
      _write(report, stderr);
      exit(1);
    case 'clean':
      _clean(
        finder: finder,
        report: report,
        dryRun: options['dry-run'] as bool,
      );
  }
}

const Set<String> _commands = <String>{'report', 'check', 'clean'};

/// Writes the unused assets of [report] and what the search left out, with
/// [hint] after a non-empty list.
void _write(UnusedAssetsReport report, IOSink out, {String? hint}) {
  if (report.unused.isEmpty) {
    out.writeln('Every asset is referenced.');
  } else {
    out.writeln('Nothing refers to ${report.unused.length} asset(s):');
    for (final asset in report.unused) {
      out.writeln('  ${asset.path}  (${asset.accessor})');
    }
    if (hint != null) out.writeln(hint);
  }
  _reportCaveats(report, out);
}

/// Says what the search left out: the assets it could not examine and the
/// code it did not count.
void _reportCaveats(UnusedAssetsReport report, IOSink out) {
  _reportBlindSpot(report, out);
  _reportDeadCode(report, out);
}

/// Says how much of the project the search could not look into.
///
/// Reading the `values` of a class uses every asset it holds, so nothing there
/// can be told apart. Without this line the report of such a project reads as
/// "everything is referenced" while a part of it was never examined.
void _reportBlindSpot(UnusedAssetsReport report, IOSink out) {
  if (report.reachedByValues.isEmpty) return;

  final containers = report.containersReachedByValues;
  out.writeln(
    '\nNot examined: ${report.reachedByValues.length} asset(s) in '
    '${containers.join(', ')} — the values of the class is read, which uses '
    'every asset it holds at once.',
  );
}

/// Lists the files whose references did not count, or the files that kept the
/// search for dead code from running.
///
/// An app started from a file the search does not take for an entry point
/// would otherwise see its code taken for dead and its assets reported, with
/// nothing saying why.
void _reportDeadCode(UnusedAssetsReport report, IOSink out) {
  if (report.missingFiles.isNotEmpty) {
    out.writeln(
      '\nDead code not looked for: ${report.missingFiles.length} file(s) are '
      'imported or listed in entry_points but are not among the scanned '
      'files. Generate them, or add their directory to scan.',
    );
    for (final file in report.missingFiles) {
      out.writeln('  $file');
    }
    return;
  }

  if (report.deadFiles.isEmpty) return;

  out.writeln(
    '\nNot counted: ${report.deadFiles.length} file(s) under lib that no entry '
    'point reaches. Entry points are the files under lib declaring main(); if '
    'the app starts elsewhere, list its files in entry_points.',
  );
  for (final file in report.deadFiles) {
    out.writeln('  $file');
  }
}

void _clean({
  required UnusedAssetsFinder finder,
  required UnusedAssetsReport report,
  required bool dryRun,
}) {
  final unused = report.unused;
  if (unused.isEmpty) {
    stdout.writeln('Nothing to delete.');
    _reportCaveats(report, stdout);
    return;
  }

  final deletion = dryRun ? finder.plan(unused) : finder.delete(unused);
  if (deletion.assets.isEmpty && deletion.variants.isEmpty) {
    stdout.writeln(
      'Nothing ${dryRun ? 'to delete' : 'deleted'}: the ${unused.length} '
      'unused asset(s) are already gone from disk. Regenerate the accessors to '
      'drop them from the code.',
    );
    return;
  }

  stdout.writeln(
    '${dryRun ? 'Would delete' : 'Deleted'} ${deletion.assets.length} file(s):',
  );
  for (final asset in deletion.assets) {
    stdout.writeln('  ${asset.path}');
  }

  if (deletion.variants.isNotEmpty) {
    stdout.writeln('Resolution variants (${deletion.variants.length}):');
    for (final variant in deletion.variants) {
      stdout.writeln('  $variant');
    }
  }
  _reportCaveats(report, stdout);
  if (dryRun) return;

  stdout.writeln(
    '\nRegenerate the accessors to drop them from the code, and remove the '
    'entries of any deleted file listed one by one in pubspec.yaml — a missing '
    'declared asset fails the build.',
  );
}

Never _fail(String message) {
  stderr.writeln(message);
  exit(64);
}
